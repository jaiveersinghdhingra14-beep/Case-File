"""
FortiGate / UTM Key-Value Firewall Log Parser.

WHY: The CyberForge competition provides network perimeter and UTM telemetry
(e.g., firex-10G.log) generated by FortiGate / FortiOS devices. These logs record
DNS requests, web filtering, traffic flows, NAT, and external command & control
or exfiltration connections using standard key=value and key="quoted value" formatting.

HOW IT OPERATES AT SCALE:
Uses compiled regular expressions and string indexing to parse key=value fields
without expensive JSON serialization. Extracts internal client IP (srcip), destination (dstip),
ports, protocol, DNS hostnames, user accounts, and action outcomes.
"""

from __future__ import annotations

import hashlib
import re
from datetime import datetime, timezone
from typing import Any

from .base import BaseParser

# Regex matching key="quoted value" or key=unquoted_value
_KV_PATTERN = re.compile(r'(\w+)=(?:"([^"]*)"|(\S+))')
_DATE_TIME_RE = re.compile(r"(\d{4}-\d{2}-\d{2})\s+(\d{2}:\d{2}:\d{2})")


def _is_priv_addr(ip: str | None) -> bool:
    if not ip:
        return False
    return ip.startswith(
        (
            "10.",
            "172.16.",
            "172.17.",
            "172.18.",
            "172.19.",
            "172.20.",
            "172.21.",
            "172.22.",
            "172.23.",
            "172.24.",
            "172.25.",
            "172.26.",
            "172.27.",
            "172.28.",
            "172.29.",
            "172.30.",
            "172.31.",
            "192.168.",
            "127.",
        )
    )


class FortigateParser(BaseParser):
    """Parses Fortinet / FortiOS UTM and Firewall log lines."""

    def can_parse(self, sample_lines: list[str]) -> bool:
        """Returns True if lines contain FortiGate signatures: devname= or devid= and date= time=."""
        hits = 0
        total = 0
        for line in sample_lines:
            s = line.strip()
            if not s:
                continue
            total += 1
            if (("devname=" in s or "devid=" in s or 'type="utm"' in s or "type=utm" in s) and "date=" in s) or (
                "srcip=" in s and "dstip=" in s and "logid=" in s
            ):
                hits += 1
        return total > 0 and (hits / total) >= 0.5

    def parse_line(
        self,
        line: str,
        source_file: str | None = None,
        byte_offset: int = 0,
        byte_length: int = 0,
    ) -> dict[str, Any] | None:
        stripped = line.strip()
        if not stripped:
            return None

        # Fast key-value extraction
        kvs: dict[str, str] = {}
        for m in _KV_PATTERN.finditer(stripped):
            k = m.group(1)
            v = m.group(2) if m.group(2) is not None else m.group(3)
            kvs[k] = v

        # --- 1. Timestamp extraction ---
        ts = None
        # Try eventtime in nanoseconds or seconds
        eventtime_str = kvs.get("eventtime")
        if eventtime_str:
            try:
                ev_val = float(eventtime_str)
                if ev_val > 1e16:  # nanoseconds
                    ev_val = ev_val / 1e9
                elif ev_val > 1e11:  # milliseconds
                    ev_val = ev_val / 1e3
                ts = datetime.fromtimestamp(ev_val, tz=timezone.utc)
            except (ValueError, OSError):
                pass

        if ts is None:
            # Fall back to date and time fields
            d_str = kvs.get("date")
            t_str = kvs.get("time")
            if d_str and t_str:
                tz_str = kvs.get("tz", "").strip('"')
                raw_dt = f"{d_str} {t_str} {tz_str}".strip()
                for fmt in ("%Y-%m-%d %H:%M:%S %z", "%Y-%m-%d %H:%M:%S"):
                    try:
                        parsed_dt = datetime.strptime(raw_dt, fmt)
                        ts = parsed_dt if parsed_dt.tzinfo else parsed_dt.replace(tzinfo=timezone.utc)
                        break
                    except ValueError:
                        continue

        if ts is None:
            return None

        # --- 2. Host identification ---
        # For network logs, internal client IP or server is the affected asset
        srcip = kvs.get("srcip")
        dstip = kvs.get("dstip")
        devname = kvs.get("devname", "firewall")

        if srcip and _is_priv_addr(srcip):
            host = srcip
            remote_ip = dstip
        elif dstip and _is_priv_addr(dstip):
            host = dstip
            remote_ip = srcip
        else:
            host = srcip or devname
            remote_ip = dstip

        # --- 3. Remote address & port ---
        dstport = self.safe_int(kvs.get("dstport"))

        # --- 4. User & Service ---
        user = kvs.get("user") or kvs.get("unauthuser")
        service = kvs.get("service") or kvs.get("proto")
        subtype = kvs.get("subtype", "")
        log_type = kvs.get("type", "")
        hostname = kvs.get("hostname") or kvs.get("domain") or kvs.get("qname")
        action = kvs.get("action", "pass")

        # --- 5. Category classification ---
        category = "network"
        if subtype in ("login", "admin", "auth") or log_type in ("auth", "login"):
            category = "authentication"
        elif subtype in ("virus", "ips", "anomaly"):
            category = "process_exec"
        elif subtype in ("webfilter", "dns"):
            category = "network"

        # --- 6. Event ID ---
        logid = kvs.get("logid", "")
        sessionid = kvs.get("sessionid", "")
        if logid and sessionid:
            event_id = f"fgt_{logid}_{sessionid}"
        elif logid:
            event_id = f"fgt_{logid}_{byte_offset}"
        else:
            event_id = hashlib.md5(stripped.encode(), usedforsecurity=False).hexdigest()[:16]

        # --- 7. MITRE & Kill Chain mapping hints ---
        mitre_ids = []
        kill_chain_stage = None
        if subtype == "dns":
            # DNS queries can be Command and Control or Discovery
            if action in ("block", "deny"):
                mitre_ids.append("T1071.004")  # DNS C2
                kill_chain_stage = "Command and Control"
        elif subtype in ("ips", "anomaly"):
            mitre_ids.append("T1190")  # Exploit Public-Facing Application
            kill_chain_stage = "Initial Access"

        # --- 8. One-line summary for LLM context ---
        parts = [f"[{host}]"]
        if user:
            parts.append(f"user={user}")
        if srcip and dstip:
            p_str = f":{dstport}" if dstport else ""
            parts.append(f"{srcip} -> {dstip}{p_str}")
        if service:
            parts.append(f"service={service}")
        if hostname:
            parts.append(f"query={hostname}")
        parts.append(f"action={action}")
        summary = " ".join(parts)

        return {
            "event_id": event_id,
            "timestamp": ts,
            "host": host,
            "source": f"fortigate_{subtype or log_type}",
            "category": category,
            "user": user,
            "pid": None,
            "ppid": None,
            "process_name": service or subtype or "firewall",
            "executable": None,
            "command_line": None,
            "file_path": None,
            "remote_address": remote_ip,
            "remote_port": dstport,
            "wazuh_rule_id": self.safe_int(kvs.get("policyid")),
            "wazuh_rule_level": None,
            "mitre_ids": mitre_ids,
            "kill_chain_stage": kill_chain_stage,
            "is_noise": False,
            "noise_reason": None,
            "group_id": None,
            "summary": summary,
            "raw_log": stripped,
            "source_file": source_file,
            "byte_offset": byte_offset,
            "byte_length": byte_length,
            "rarity_score": None,
            "is_seed": False,
        }
